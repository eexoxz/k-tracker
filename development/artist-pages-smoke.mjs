import { chromium } from "file:///C:/Users/USER/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  const errors = [];
  const page = await context.newPage();
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => {
    localStorage.setItem("k-tracker:preferences", JSON.stringify({ scene: "kpop", selectedArtist: "aespa", activeView: "releases" }));
    localStorage.setItem("k-tracker:watchlist", "[]");
  });
  await page.goto("http://localhost:5174");
  await page.getByRole("heading", { name: "aespa", exact: true }).waitFor();
  const members = page.getByRole("region", { name: "aespa members" });
  await members.getByRole("button", { name: "KARINA", exact: true }).waitFor({ timeout: 60000 });
  await page.getByRole("button", { name: "Refresh", exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector(".sync-button").disabled, { timeout: 60000 });
  assert.equal(await members.locator(".member-row").count(), 4);
  assert.ok(await members.locator('a[href*="instagram.com"]').count() >= 3);
  assert.ok(await page.locator(".release-card").count() > 0);
  assert.ok(await page.locator(".release-card").count() <= 12);
  await page.getByRole("button", { name: "More releases", exact: true }).click();
  assert.ok(await page.locator(".release-card").count() > 12);
  await page.screenshot({ path: "outputs/aespa-desktop.png", fullPage: false });
  await page.getByRole("button", { name: "News", exact: true }).click();
  assert.ok((await page.locator(".public-source-card").first().getAttribute("href")).includes("aespa"));
  await page.getByRole("textbox", { name: "Find any artist" }).fill("KISS OF LIFE");
  const results = page.getByRole("region", { name: "Online artist results" });
  await results.getByRole("button").first().waitFor({ timeout: 60000 });
  console.log("Online candidates:", await results.innerText());
  await results.getByRole("button").filter({ hasText: "KISS OF LIFE" }).first().click();
  await page.getByRole("heading", { name: "KISS OF LIFE", exact: true }).first().waitFor({ timeout: 30000 });
  const otherMembers = page.getByRole("region", { name: "KISS OF LIFE members" });
  await otherMembers.locator(".member-row").first().waitFor({ timeout: 60000 });
  await page.waitForFunction(() => !document.querySelector(".sync-button").disabled, { timeout: 60000 });
  console.log("Other group members:", await otherMembers.innerText());
  assert.equal(await otherMembers.locator(".member-row").count(), 4);
  assert.ok(await page.locator(".release-card").count() > 0);
  await page.screenshot({ path: "outputs/kiss-of-life-desktop.png", fullPage: false });
  const requests = [];
  page.on("request", (request) => { if (request.url().includes("musicbrainz.org/ws")) requests.push(request.url()); });
  await page.getByRole("button", { name: "aespa", exact: false }).filter({ has: page.locator("strong") }).first().click();
  await page.getByRole("heading", { name: "aespa", exact: true }).first().waitFor();
  assert.equal(requests.length, 0, "cached artist should not refetch");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "outputs/aespa-mobile.png", fullPage: false });
  await members.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "outputs/aespa-members-mobile.png", fullPage: false });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await members.getByRole("button", { name: "KARINA", exact: true }).click();
  await page.getByRole("heading", { name: "KARINA", exact: true }).first().waitFor();
  await page.waitForFunction(() => !document.querySelector(".sync-button").disabled, { timeout: 60000 });
  assert.equal(await page.locator(".artist-members-section").count(), 0);
  assert.ok(await page.locator('.source-strip a[href*="instagram.com"]').count() > 0);
  assert.deepEqual(errors, []);
  console.log("PASS: aespa, online group, member page, news links, cached switching, mobile overflow, and no runtime errors.");
} finally {
  await browser.close();
}
